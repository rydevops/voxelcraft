// Lit pixels of a line of text as [x, y] cells (letters one blank column apart); unknown characters are skipped
export function textPixels(text) {
  const out = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const g = GLYPHS[ch];
    if (!g) return;
    g.forEach((row, y) => [...row].forEach((bit, x) => { if (bit === '1') out.push([i * (GLYPH_W + 1) + x, y]); }));
  });
  return out;
}
export const textWidth = (text) => text.length * (GLYPH_W + 1) - 1;
